import { fireEvent, render, screen } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { QuadraticGraph } from '../src/shared/lesson/quadratic-graph';
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it('graph pointer gestures never move x; the slider remains keyboard accessible', () => {
  render(<QuadraticGraph/>);
  const graph = screen.getByRole('img', { name: /График y/ });
  const probe = screen.getByLabelText('Абсцисса исследуемой точки x') as HTMLInputElement;
  fireEvent.pointerMove(graph, { clientX: 400, clientY: 180 });
  fireEvent.pointerDown(graph, { clientX: 400, clientY: 180 });
  fireEvent.pointerUp(graph, { clientX: 400, clientY: 180 });
  expect(probe.value).toBe('0');
  fireEvent.change(probe, { target: { value: '3.5' } });
  expect(probe.value).toBe('3.5');
  expect(probe.getAttribute('aria-valuetext')).toContain('3,5');
});
it('only actual control input interrupts an animated reset', () => {
  const cancel = vi.fn();
  vi.stubGlobal('requestAnimationFrame', vi.fn(() => 123));
  vi.stubGlobal('cancelAnimationFrame', cancel);
  vi.stubGlobal('matchMedia', () => ({ matches: false }));
  render(<QuadraticGraph/>);
  fireEvent.change(screen.getByRole('slider', { name: 'Коэффициент c' }), { target: { value: '5' } });
  fireEvent.click(screen.getByRole('button', { name: 'Сбросить коэффициенты' }));
  fireEvent.pointerDown(screen.getByRole('img', { name: /График y/ }));
  fireEvent.pointerUp(screen.getByRole('img', { name: /График y/ }));
  expect(cancel).not.toHaveBeenCalled();
  fireEvent.change(screen.getByLabelText('Абсцисса исследуемой точки x'), { target: { value: '2' } });
  expect(cancel).toHaveBeenCalledWith(123);
});
