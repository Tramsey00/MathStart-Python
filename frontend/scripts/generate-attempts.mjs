// Only public schemas, never exchange fixtures or server hint/solution data.
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import Ajv from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';
const root=fileURLToPath(new URL('../..',import.meta.url));
const dto=JSON.parse(readFileSync(resolve(root,'specs/api/schemas/dto-v1.schema.json'),'utf8'));
const policy=JSON.parse(readFileSync(resolve(root,'specs/api/http-policy-v1.json'),'utf8'));
const operations=policy.operations.filter(o=>o.tag==='Attempts');
const names=[...new Set(operations.flatMap(o=>[o.request,o.response]).filter(Boolean).concat(
  ['PendingAttemptResponse','ConflictEnvelope','AuthenticationError','ForbiddenError','BadRequestError',
   'NotFoundError','RateLimitError','UnavailableError']))];
const ajv=new Ajv({strict:false,ownProperties:true,coerceTypes:false,code:{source:true,esm:true}});
addFormats(ajv);
ajv.addSchema(dto);
const exportsMap={};
for(const name of names){
  if(!dto.$defs[name])throw Error('Unknown DTO '+name);
  const id=dto.$id+'#/$defs/'+name;
  ajv.getSchema(id);exportsMap[name]=id;
}
const imports=new Map();
let code=standalone(ajv,exportsMap).replace(/require\("([^"]+)"\)/g,(_,path)=>{
  const helpers={
    'ajv/dist/runtime/ucs2length':['unicodeLength','import * as unicodeLength from "./schema-helpers.mjs";'],
    'ajv-formats/dist/formats':['formatHelpers','import formatHelpers from "ajv-formats/dist/formats.js";'],
  };
  const helper=helpers[path];
  if(!helper)throw Error('Unexpected standalone helper: '+path);
  imports.set(path,helper[1]);return helper[0];
});
if(/\brequire\s*\(/.test(code))throw Error('CommonJS remained in browser validator');
code='// Generated by generate-attempts.mjs from canonical DTOs; no fixture payloads.\n'
  +[...imports.values()].join('\n')+'\n'+code+'\n';
const outputs={
 'attempt-validators.mjs':code,
 'attempt-validators.d.mts':names.map(n=>`export declare const ${n}:(value:unknown)=>boolean;`).join('\n')+'\n',
 'attempt-contracts.ts':"// Generated canonical Attempt types and operation policy.\nimport type {components} from './openapi';\nexport interface AttemptContracts {\n"
  +operations.map(o=>`${o.operation_id}:{request:${o.request?`components['schemas']['${o.request}']`:'never'};response:components['schemas']['${o.response}']};`).join('\n')
  +'\n}\nexport const attemptOperations='+JSON.stringify(Object.fromEntries(operations.map(o=>[o.operation_id,{
    path:o.path,method:o.method.toUpperCase(),receipt:o.idempotency,request:o.request,response:o.response} ])),null,2)+' as const;\n',
};
for(const [name,code] of Object.entries(outputs)){
 const path=resolve(root,'frontend/src/shared/api/generated',name);
 if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==code)throw Error('Stale '+name);}
 else writeFileSync(path,code);
}
