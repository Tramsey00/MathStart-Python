def inline_formula(html):
    return '<span style="white-space:nowrap">' + html + '</span>'

def FP(value, exponent):
    base = '<span class="ms-tall-paren">(</span>' + value + '<span class="ms-tall-paren">)</span>'
    return P(base, exponent).replace('class="v2-power"', 'class="v2-power ms-fraction-power"', 1)

def RF(top, bottom):
    return R(F(top, bottom)).replace('class="v2-root"', 'class="v2-root ms-root-fraction"', 1)

